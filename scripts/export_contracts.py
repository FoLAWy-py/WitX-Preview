"""Generates TypeScript types for the Web app from the Python API contracts.

uv run python scripts/export_contracts.py          # write apps/web/src/api/types.gen.ts
uv run python scripts/export_contracts.py --check  # fail if the file is out of date
"""

import argparse
import inspect
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from witx_contracts import api

OUTPUT = Path(__file__).resolve().parents[1] / "apps/web/src/api/types.gen.ts"
HEADER = "// Generated by scripts/export_contracts.py from witx_contracts.api. Do not edit.\n"


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(_ts(s) for s in schema[key]))
    kind = schema.get("type")
    if kind == "array":
        item = _ts(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {_ts(extra) if isinstance(extra, dict) and extra else 'unknown'}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def _literal(value: object) -> str:
    return f'"{value}"' if isinstance(value, str) else str(value).lower()


def _interface(name: str, schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, sub in schema.get("properties", {}).items():
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {_ts(sub)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    models = [
        obj
        for _, obj in inspect.getmembers(api, inspect.isclass)
        if issubclass(obj, BaseModel) and obj.__module__ == api.__name__ and obj is not api.Wire
    ]
    definitions: dict[str, dict[str, Any]] = {}
    for model in models:
        schema = model.model_json_schema(mode="validation", ref_template="#/$defs/{model}")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    blocks = [_interface(name, definitions[name]) for name in sorted(definitions)]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            sys.exit(f"{OUTPUT} is out of date; run scripts/export_contracts.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
